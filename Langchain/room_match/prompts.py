# ===== 提示词获取函数 =====
def get_prompt(prompt_name: str) -> PromptTemplate:
    """获取指定名称的提示词模板"""
    prompts = {
        'http_info_extraction': HTTP_INFO_EXTRACTION_PROMPT,
        'agent_room_matching': AGENT_ROOM_MATCHING_PROMPT,
    }

    return prompts.get(prompt_name)


def get_all_prompts() -> dict:
    """获取所有提示词模板"""
    return {
        'http_info_extraction': HTTP_INFO_EXTRACTION_PROMPT,
        'agent_room_matching': AGENT_ROOM_MATCHING_PROMPT,
    }
